package dev.gr0mi4.ohealthinsights.drive

import java.time.Instant
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter
import dev.gr0mi4.ohealthinsights.BuildConfig
import dev.gr0mi4.ohealthinsights.EngineExportResult

class ReportBuilder(
    private val metricsStore: MetricsStore,
) {
    fun buildMarkdown(
        summary: EngineExportResult,
        exportedAt: Instant,
        sessionWorkouts: List<WorkoutMetric>,
        warnings: List<String> = summary.warnings,
        reportDays: Int = 14,
    ): String {
        val recent = metricsStore.recentDays(reportDays)
        val formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm 'UTC'").withZone(ZoneOffset.UTC)
        return buildString {
            appendLine("# OHealth Insights Report")
            appendLine()
            appendLine("- App version: ${BuildConfig.VERSION_NAME}")
            appendLine("- Exported at: ${formatter.format(exportedAt)}")
            appendLine("- Sync mode: ${summary.syncMode}")
            appendLine("- Raw records: ${summary.rawRecordCount}")
            appendLine("- Derived summaries: ${summary.derivedRecordCount}")
            appendLine("- Non-empty record types: ${summary.nonEmptyTypes}")
            appendLine()
            appendLine("## Analysis contract")
            appendLine()
            appendLine("- Canonical daily steps: `Steps (OHealth)` when present; use `Steps (dedup)` only as an explicit fallback/debug value.")
            appendLine("- A row for the export day may be partial when the sync ran before the local day ended.")
            appendLine("- Raw exercise records are activity records, not automatically separate training sessions.")
            appendLine("- Generic `Workout` may be walking, warm-up/cool-down, or an adjacent fragment; `Freestyle workout` is semantically ambiguous.")
            appendLine("- Classify ambiguous sessions using duration, kcal/min, HR/HR zones, steps/step rate, distance, overlap/adjacency, context, and user-confirmed ground truth.")
            appendLine("- Separate deliberate training from light activity/everyday walking; if evidence is insufficient, keep the session unclassified rather than guessing.")
            appendLine("- Full interpretation rules: `docs/ANALYSIS_CONTRACT.md` in the ohealth-insights repository.")
            appendLine()
            appendLine("## Last $reportDays days")
            appendLine()
            appendLine("| Date | Steps (dedup) | Steps (OHealth) | Calories (kcal) | Workouts | Sleep (min) |")
            appendLine("| --- | ---: | ---: | ---: | ---: | ---: |")
            recent.forEach { day ->
                appendLine(
                    "| ${day.date} | ${day.stepsTotal ?: "—"} | ${day.stepsOHealth ?: "—"} | " +
                        "${formatDouble(day.totalCaloriesKcal)} | ${day.workoutCount} | " +
                        "${day.sleepMinutes ?: "—"} |",
                )
            }
            if (sessionWorkouts.isNotEmpty()) {
                appendLine()
                appendLine("## Exercise records in this sync")
                appendLine()
                appendLine("*These are source exercise records and must not be interpreted as distinct training sessions without classification.*")
                appendLine()
                sessionWorkouts.forEach { workout ->
                    appendLine(
                        "- ${workout.title ?: "Workout"}: " +
                            "${formatter.format(workout.startTime)} → ${formatter.format(workout.endTime)}, " +
                            "${formatDouble(workout.caloriesKcal)} kcal",
                    )
                }
            }
            if (warnings.isNotEmpty()) {
                appendLine()
                appendLine("## Warnings")
                warnings.forEach { appendLine("- $it") }
            }
            appendLine()
            appendLine("---")
            appendLine("*Generated by OHealth Insights for ChatGPT / personal analysis.*")
        }
    }

    fun buildCsv(reportDays: Int = 90): String = buildString {
        appendLine("date,steps_total,steps_ohealth,calories_kcal,workout_count,workout_calories_kcal,sleep_minutes")
        metricsStore.recentDays(reportDays).forEach { day ->
            appendLine(
                listOf(
                    day.date,
                    day.stepsTotal?.toString() ?: "",
                    day.stepsOHealth?.toString() ?: "",
                    day.totalCaloriesKcal?.toString() ?: "",
                    day.workoutCount,
                    day.workoutCaloriesKcal?.toString() ?: "",
                    day.sleepMinutes?.toString() ?: "",
                ).joinToString(","),
            )
        }
    }

    private fun formatDouble(value: Double?): String =
        if (value == null) "—" else "%.0f".format(value)
}
